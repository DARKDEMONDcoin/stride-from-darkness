/**
 * حارس أخير قبل النشر على أي منصة.
 *
 * قواعد الامتثال مكتوبة في تعليمات الموظفين، لكن التعليمات نصيحة يلتزم بها
 * النموذج غالباً لا دائماً. هذا الملف يحوّل أخطر القواعد إلى فحص حتمي يُوقف
 * النشر ويشرح السبب لصاحب العمل، بدل نشر نص قد يعرّض حسابه للمساءلة.
 *
 * محايد (متصفح + خادم) حتى تستعمله لوحة النشر والطابور بنفس المنطق.
 */

type Rule = { re: RegExp; reason: string };

/** وعود مطلقة وادعاءات تفوّق لا يجوز نشرها بلا دليل. */
const ABSOLUTE: Rule[] = [
  {
    re: /(?:نتيجة\s+مضمونة|نضمن\s+لك|مضمون\s+(?:100|١٠٠)\s*%|ضمان\s+(?:الشفاء|النتيجة)|بدون\s+أي\s+مخاطر)/u,
    reason: "وعد مضمون بالنتيجة — ممنوع نظاماً وإعلانياً.",
  },
  {
    re: /(?:الأفضل|الأول|رقم\s*(?:١|1))\s+(?:في|على)\s+(?:السعودية|مصر|الإمارات|الخليج|الوطن\s+العربي|العالم)/u,
    reason: "ادعاء تفوّق مطلق بلا مصدر موثّق.",
  },
];

/** ادعاءات صحية وطبية تحتاج ترخيصاً ولا تُنشر من حساب تجاري. */
const MEDICAL: Rule[] = [
  {
    re: /(?:يعالج|علاج\s+(?:نهائي|مؤكد|مضمون)|يشفي|الشفاء\s+التام|بديل\s+عن\s+(?:الطبيب|الدواء))/u,
    reason: "ادعاء علاجي/طبي يحتاج ترخيصاً — لا يُنشر.",
  },
];

/** وعود عائد مالي — محظورة في أنظمة الإعلان بأسواقنا. */
const FINANCIAL: Rule[] = [
  {
    re: /(?:أرباح\s+مضمونة|ربح\s+مضمون|عائد\s+مضمون|تضاعف\s+أموالك|استثمار\s+بلا\s+(?:خسارة|مخاطر))/u,
    reason: "وعد عائد مالي مضمون — محظور في أنظمة الإعلان.",
  },
];

/** أسطر موجّهة لصاحب العمل تسرّبت داخل المنشور. */
const OWNER_NOTE: Rule[] = [
  {
    re: /^\s*[-•*]?\s*(?:الموضوع|مؤشر\s+(?:الأداء|الاداء|القياس)|التوقيت\s+المقترح|الجمهور\s+المستهدف|زاوية\s+المحتوى)\s*[:：]/mu,
    reason: "النص يحتوي سطراً موجّهاً لك لا للجمهور — احذفه قبل النشر.",
  },
];

const RULES: Rule[] = [...ABSOLUTE, ...MEDICAL, ...FINANCIAL, ...OWNER_NOTE];

/**
 * يعيد قائمة أسباب تمنع النشر. قائمة فارغة = النص آمن للنشر.
 * لا يعدّل النص إطلاقاً — القرار لصاحب العمل.
 */
export function publishBlockers(text: string | null | undefined): string[] {
  if (!text || !text.trim()) return ["نص المنشور فارغ."];
  const out: string[] = [];
  for (const rule of RULES)
    if (rule.re.test(text) && !out.includes(rule.reason)) out.push(rule.reason);
  return out;
}
