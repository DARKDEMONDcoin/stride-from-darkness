/**
 * حدود الاختصاص بين الموظفين.
 * كل خدمة يملكها موظف واحد فقط: النشر على السوشيال لسِراج وحده، والسيو لنور،
 * والبريد والمواعيد لإيفا… إلخ. إن جاء الطلب لغير صاحبه يوجّه الموظف المستخدم فوراً.
 */
import { detectHandoff, isDecisivelyMine } from "./handoff";
import { employeeDirectory, type EmployeeId } from "./team-knowledge";

const OWNERSHIP: Record<string, string> = {
  sonny:
    "صناعة محتوى السوشيال والنشر والجدولة على إنستجرام وفيسبوك وتيك توك ولينكدإن وإكس ويوتيوب وبنترست",
  nour: "السيو والمقالات وصفحات الموقع والنشر على المدونة (ووردبريس/Shopify/Webflow/Ghost)",
  eva: "البريد والمواعيد والتقويم والتنظيم اليومي",
  sam: "المبيعات والعملاء المحتملين وعروض الأسعار والـ CRM",
  dana: "التصميم والهوية البصرية والعروض التقديمية",
  adam: "الأرقام والتقارير وأداء الحملات والميزانيات",
};

/** كتلة تعليمات تمنع الموظف من أداء عمل زميله وتجعله يحوّل الطلب فوراً. */
export function scopeBoundaryBlock(employeeId: string, message?: string): string {
  const me = employeeDirectory[employeeId as EmployeeId];
  if (!me) return "";

  const others = Object.entries(OWNERSHIP)
    .filter(([id]) => id !== employeeId)
    .map(([id, what]) => `- ${employeeDirectory[id as EmployeeId]?.name ?? id}: ${what}`)
    .join("\n");

  const lines = [
    "## حدود اختصاصك (إلزامي)",
    `اختصاصك أنت: ${OWNERSHIP[employeeId] ?? me.role}.`,
    "توزيع بقية الخدمات على زملائك:",
    others,
    "قاعدة صارمة: لا تنفّذ خدمة يملكها زميل. النشر والجدولة على منصات التواصل من اختصاص سِراج وحده، ولا يقدّمها أي موظف آخر ولا يَعِد بها.",
    "نشر المقالات وصفحات الموقع على المدونة (ووردبريس/Ghost/Shopify/Webflow) من اختصاص نور وحدها: هي تكتب المقال وتنشره بنفسها ولا تحوّله إلى سِراج.",
    "فصل التصميم عن النشر: الشكل البصري لأي مخرج (ستوري، بوست، كاروسيل، بانر، غلاف) — المقاس والألوان والخطوط والمناطق الآمنة والبريف البصري — من اختصاص دانة. سِراج يملك نص المنشور والهاشتاقات والجدولة والنشر. إذا قال المستخدم «صمّم/صممي/تصميم/بريف بصري» فالطلب لدانة حتى لو ذُكر اسم منصة اجتماعية، وتنفّذه هي ولا تحوّله. وإذا قال «اكتب منشور/انشر/جدول» فهو لسِراج حتى لو ذُكر شكل بصري.",
    "التنفيذ الحقيقي يمرّ دائماً عبر تكاملاتك المربوطة: إن كان الطلب قابلاً للتنفيذ بإجراء على تكاملك، جهّز الإجراء بقيمه كاملة واعرضه للاعتماد بدل الاكتفاء بالنصيحة. وإن كانت المنصة غير مربوطة اطلب ربطها بسبب واحد قصير.",
    "إن كان الطلب من اختصاص زميل: قل بجملة واحدة ودودة وبلا اعتذار إن الزميل الفلاني هو الأنسب ولماذا، أخبر المستخدم أن زر «التوجّه إلى …» تحت ردك ينقل طلبه كما هو، ثم توقف. لا تكتب المخرج نيابةً عنه ولا خطة تنفيذ مفصّلة.",
    "بنية التسليم الإلزامية عند التحويل — ثلاثة أسطر لا أكثر: (١) «هذا من اختصاص [اسم الزميل] — [سبب من ست كلمات]»، (٢) `### ما سأنقله له` سطر واحد يلخّص الطلب والسياق المتفق عليه حتى الآن (القرارات، الأرقام، المواعيد، اسم المنتج) كي لا يعيد الزميل السؤال من الصفر، (٣) «اضغط زر التوجّه إلى [اسم الزميل] تحت ردي». استخدم اسم الزميل العربي كما هو مكتوب في قائمة الزملاء أعلاه، وممنوع تحويل الطلب إلى «الفريق» أو «زميل مختص» بلا اسم.",
    "إن كان في الطلب جزء يخصك فعلاً: نفّذ جزءك أنت فقط، وحوّل الباقي للزميل بنفس الطريقة.",
    "جملة التحويل لا تُكتب أبداً داخل مخرج يُرسل لطرف ثالث (نص رسالة أو منشور أو مقال): إمّا أن تحوّل بسطر واحد بلا مخرج، أو تسلّم المخرج نظيفاً وتذكر التحويل بعده منفصلاً.",
  ];

  if (message && isDecisivelyMine(message, employeeId)) {
    lines.push(
      "تنبيه لهذه الرسالة تحديداً: المستخدم طلب منك خدمة من صميم اختصاصك بفعل أمر صريح. نفّذها بنفسك كاملة، وممنوع منعاً باتاً تحويلها إلى أي زميل مهما ورد في الطلب من أسماء منصات.",
    );
  }

  const handoff = message ? detectHandoff(message, employeeId) : null;
  if (handoff) {
    lines.push(
      `تنبيه لهذه الرسالة تحديداً: طلب المستخدم (${handoff.topic}) من اختصاص ${handoff.name} — ${handoff.role}. وجّهه إليه الآن ولا تنفّذ الطلب.`,
    );
  }

  return lines.join("\n");
}
