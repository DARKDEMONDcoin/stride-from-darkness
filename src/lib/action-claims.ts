/**
 * حارس الصدق: النموذج لا ينشر شيئاً بنفسه — النشر يمرّ حصراً عبر طابور النشر
 * (‎social_posts‎ + Pipedream). لذلك نمنع أي ادعاء بأن النشر/الإرسال قد تم،
 * ونصحّح النص إن ادّعى ذلك.
 */

/** قواعد تُحقن في تعليمات النظام لكل موظف. */
export const actionTruthRules = [
  "لا تنفّذ أي إجراء خارجي بنفسك: لا تنشر ولا تجدول ولا ترسل ولا تربط حسابات.",
  "ممنوع منعاً تاماً أن تقول «تم النشر» أو «نشرته» أو «تم الإرسال» أو «تمت الجدولة» أو ما يشبهها.",
  "أنت تسلّم المحتوى جاهزاً فقط. يوجد زر «انشر الآن» وزر «جدولة» أسفل كل منشور تكتبه هنا — أرشد المستخدم إليهما.",
  "ممنوع أن تقول إنك لا تملك صلاحية أو لا يمكنك النشر: الصحيح أن النشر يتم بضغطة زر «انشر الآن» أسفل المنشور، وإن لم يكن الحساب مربوطاً يظهر زر «اربط حساباتك».",
].join("\n");

/** أنماط ادعاء تنفيذ فعل خارجي. */
const CLAIM =
  /(تمّ?\s*(ال)?(نشر|الجدولة|جدولة|الإرسال|إرسال|الرفع|رفع)|نشرت(ه|ها|هم)?|جدولت(ه|ها)?|أرسلت(ه|ها)?|رفعت(ه|ها)?\s*على|نُشر|نشر\s*المنشور|أصبح\s*(المنشور|المقال)?\s*(حياً|حيا|منشوراً|منشورا)|هو\s*(الآن\s*)?(حي|منشور)\s*(الآن)?|صار\s*(منشوراً|منشورا|حياً|حيا)|(المنشور|المقال|الرسالة)\s*(الآن\s*)?(منشور|مُرسلة|مرسلة)\s*(الآن)?|published successfully|is\s+now\s+live|went\s+live)/;

const SOFTEN: [RegExp, string][] = [
  [/تمّ?\s*النشر\s*بنجاح/g, "المنشور جاهز للنشر"],
  [/تمّ?\s*النشر/g, "المنشور جاهز للنشر"],
  [/تمّ?\s*(الجدولة|جدولة)/g, "الموعد المقترح للجدولة"],
  [/تمّ?\s*(الإرسال|إرسال)/g, "الرسالة جاهزة للإرسال"],
  [/نشرته|نشرتها|نشرتهم/g, "جهّزته لك للنشر"],
  [/جدولته|جدولتها/g, "اقترحت موعده"],
  [/أرسلته|أرسلتها/g, "جهّزته لك للإرسال"],
  // صيغ «صار حياً» و«نُشر» — ادعاء تنفيذ بصياغة أخرى.
  [/نُشر\s*(المنشور|المقال)?\s*(بنجاح)?/g, "جاهز للنشر"],
  [/أصبح\s*(المنشور|المقال)?\s*(حياً|حيا|منشوراً|منشورا)/g, "جاهز للنشر بضغطة"],
  [/صار\s*(حياً|حيا|منشوراً|منشورا)/g, "جاهز للنشر بضغطة"],
  [/هو\s*(الآن\s*)?(حي|منشور)(\s*الآن)?/g, "جاهز للنشر بضغطة"],
  [/is\s+now\s+live|went\s+live/gi, "ready to publish"],
  // صيغ كان CLAIM يلتقطها وتبقى في النص بلا تخفيف، فيتناقض التنبيه مع الجملة.
  [/رفعته|رفعتها|رفعتهم/g, "جهّزته لك للرفع"],
  [/تمّ?\s*(الرفع|رفع)/g, "جاهز للرفع"],
  [/نشر\s*المنشور\s*(بنجاح)?/g, "المنشور جاهز للنشر"],
  [/(المنشور|المقال|الرسالة)\s*(الآن\s*)?(منشور|مُرسلة|مرسلة)(\s*الآن)?/g, "$1 جاهز للإرسال أو النشر"],
  [/published\s+successfully/gi, "ready to publish"],
];

/**
 * يصحّح النص إذا ادّعى تنفيذ نشر/إرسال لم يحدث، ويضيف تنبيهاً واضحاً.
 * `connected` = المنصات المربوطة فعلاً (لعرض الخطوة التالية الصحيحة).
 */
export function sanitizeActionClaims(text: string, connected: string[] = []): string {
  if (!text || !CLAIM.test(text)) return text;

  let out = text;
  for (const [pattern, replacement] of SOFTEN) out = out.replace(pattern, replacement);

  const next = connected.length
    ? "اعتمده من صفحة الاعتمادات ثم اضغط «انشر الآن» أو حدّد موعداً."
    : "اربط حسابك أولاً من صفحة التكاملات، ثم اعتمد المنشور واضغط «انشر الآن».";

  return `> ⚠️ لم يُنشر بعد — المحتوى جاهز والنشر بضغطة واحدة منك. ${next}\n\n${out.trim()}`;
}
