/** كتلة ملف العلامة من الـ profile المخزَّن في مساحة العمل. */
export function businessProfileBlock(
  profile: unknown,
  website?: string | null,
  country?: string | null,
): string {
  if (!profile || typeof profile !== "object") return "";
  const p = profile as Record<string, unknown>;
  const str = (k: string) =>
    typeof p[k] === "string" && (p[k] as string).trim() ? (p[k] as string).trim() : "";
  const list = (k: string) =>
    Array.isArray(p[k])
      ? ((p[k] as unknown[]).filter((x) => typeof x === "string").slice(0, 8) as string[])
      : [];
  const rows = [
    str("name") ? `- اسم العلامة كما يُكتب حرفياً في كل مخرج: ${str("name")}` : "",
    str("industry") ? `- المجال: ${str("industry")}` : "",
    website ? `- الموقع: ${website}` : "",
    country ? `- الدولة الرئيسية: ${country}` : "",
    str("summary") ? `- ملخص النشاط: ${str("summary")}` : "",
    list("products").length ? `- المنتجات/الخدمات: ${list("products").join("، ")}` : "",
    str("audience") ? `- الجمهور: ${str("audience")}` : "",
    str("usp") ? `- ما يميزهم: ${str("usp")}` : "",
    list("locations").length ? `- المدن/الفروع: ${list("locations").join("، ")}` : "",
    list("competitors").length ? `- منافسون محتملون: ${list("competitors").join("، ")}` : "",
    str("dialect") ? `- لهجة الموقع: ${str("dialect")}` : "",
    list("socials").length ? `- حسابات التواصل المكتشفة: ${list("socials").join("، ")}` : "",
    str("platform") ? `- منصة الموقع: ${str("platform")}` : "",
    list("contacts").length ? `- وسائل التواصل: ${list("contacts").join("، ")}` : "",
  ].filter(Boolean);
  if (!rows.length) return "";
  return `## ملف العلامة (مستخرج تلقائياً من موقعها — اعتمده كحقائق ما لم يصحّحه المستخدم)\n${rows.join("\n")}`;
}

/**
 * دستور الإتقان — الطبقة التي ترفع كل موظف إلى مستوى «أفضل من في مجاله»:
 * منهج تفكير، عمق مهني، صدق، وتنفيذ لا يتوقف عند الكلام.
 */
/** قاعدة اللغة واللهجة — مصدر واحد، تتبع دولة العلامة. */
export function languageBlock(country?: string | null, chosenDialect?: string | null): string {
  const c = (country ?? "").toLowerCase();
  const picked = (chosenDialect ?? "").trim();
  const detected = /egypt|مصر|eg\b/.test(c)
    ? "المصرية الخفيفة المفهومة"
    : /saudi|السعود|ksa|sa\b/.test(c)
      ? "السعودية البيضاء (نجدية معتدلة بلا مبالغة)"
      : /emirat|امارات|الإمارات|uae|ae\b/.test(c)
        ? "الخليجية الإماراتية المعتدلة"
        : /kuwait|الكويت|qatar|قطر|bahrain|البحرين|oman|عمان/.test(c)
          ? "الخليجية المعتدلة"
          : /jordan|الأردن|lebanon|لبنان|syria|سوريا|palest|فلسطين/.test(c)
            ? "الشامية المفهومة"
            : /morocc|المغرب|algeri|الجزائر|tunis|تونس/.test(c)
              ? "الدارجة المغاربية المخففة مع فصحى مبسّطة"
              : "فصحى معاصرة مبسّطة قريبة من الكلام اليومي";
  const dialect = picked || detected;
  return [
    "## اللغة واللهجة",
    `- جمهور العلامة: ${country?.trim() || "السوق العربي"}. لهجة المحتوى الموجّه للجمهور: ${dialect}${picked ? " (اختارها المالك بنفسه في إعدادات الحساب — التزم بها حرفياً وقدّمها على أي لهجة أخرى)" : ""}.`,
    "- التقارير والخطط والتحليلات: فصحى واضحة قصيرة الجمل، بلا لهجة وبلا زخرفة.",
    "- البريد الرسمي والمقترحات: فصحى مهذّبة محايدة.",
    "- ممنوع: ترجمة حرفية من الإنجليزية، مصطلح أجنبي له مقابل عربي شائع، خلط لهجتين في نص واحد، أو فصحى متقعّرة في منشور سوشيال.",
    "- المصطلحات التقنية المتعارف عليها (SEO، CTR، ROAS) تُكتب كما هي مع شرحها بثلاث كلمات أول مرة فقط.",
    "- إن كتب المستخدم بلهجة معيّنة أو بالإنجليزية، جاريه في المحادثة وابقَ على لهجة الجمهور في المخرج نفسه.",
  ].join("\n");
}

