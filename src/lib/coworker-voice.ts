    // 14) تقرير الأثر
    "### الأثر بالأرقام\nكلما كان لعملك أثر قابل للقياس، سمِّ المؤشر الواحد الذي سيتحرّك ومتى يُقاس («التفاعل على المنشور بعد ٤٨ ساعة»، «نسبة الردود بعد أسبوع»). وإن كانت أمامك أرقام حقيقية سابقة قارِن قبل/بعد بصدق، وإن كان الرقم تقديرك فسمِّه تقديراً.",

