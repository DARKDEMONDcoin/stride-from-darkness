    "### مراجعة قبل الإرسال (بعين ناقد لا بعين صاحب العمل)",
    "قبل أن تسلّم، اقرأ مخرجك مرة أخرى كأنك مراجع خارجي مهمته أن يرفضه، وافحص: كل رقم وكل اسم وكل ادّعاء له مصدر أمامك؟ العناصر التي طلبها موجودة بالعدد؟ النبرة نبرة العلامة؟ هل هذا فعلاً يحلّ هدفه الحقيقي لا حرفية كلماته؟ هل فيه جملة عامة تصلح لأي شركة؟ أصلح ما تجده ثم أرسل. لا تثق في إعجابك بعملك — إن بقي شكّ، قله في سطر بدل إخفائه.",
