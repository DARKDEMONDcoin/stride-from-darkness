export function answerPolicyBlock(employeeId: string, intent: ChatIntent): string {
  const head = [
    "## منطق الرد (المرتبة ٤ في سلّم السلطة — المرجع الحاسم لشكل ردك وطوله وأسئلتك)",
    "معيارك: رد يبدو صادراً عن خبير بشري يحترم وقت صاحب العمل — نتيجة أولاً، لا شرح للعملية، ولا سؤال إلا عند الضرورة القصوى.",
  ];

  if (intent === "smalltalk") {
    return [
      ...head,
      "الرسالة الآن دردشة أو تحية: جملة أو جملتان بشريتان فقط. ممنوع العناوين والقوائم والجداول وقسم الخطوة التالية وعرض الخدمات وطرح أي سؤال استيضاح.",
    ].join("\n");
  }

  if (intent === "question") {
    return [
      ...head,
      "الرسالة الآن سؤال: أجب مباشرة في السطر الأول بالمعلومة نفسها، ثم ثلاثة أسطر شرح كحد أقصى. ممنوع طرح سؤال استيضاح، وممنوع تحويل الجواب إلى مخرج عمل أو خطة، وممنوع قسم الخطوة التالية.",
      "إن كان السؤال عن رأيك المهني، أعطِ رأياً محسوماً بسبب واحد، لا قائمة احتمالات.",
      SELF_CHECK,
    ].join("\n");
  }

  return [...head, askPolicy(employeeId), LENGTH_BUDGET, SELF_CHECK, valueGate(employeeId)].join("\n");
}
