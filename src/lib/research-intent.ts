/**
 * بوابة نية البحث — مصدر واحد يقرر: هل هذه الرسالة تستحق بحثاً حياً؟
 *
 * قبل هذا الملف كان البحث ينطلق بكلمات زمنية فقط («آخر، اليوم، سعر، خبر»)،
 * فجملة مثل «ابحث لي عن أفضل منافس في السوق» كانت تُجاب من معرفة النموذج المخزّنة
 * عند خمسة موظفين من ستة. هنا نلتقط نية البحث الصريحة مهما كان الموظف.
 */

/** أفعال طلب البحث الصريحة — عربية ولهجات ودارجة وإنجليزية. */
const EXPLICIT =
  /(ابحث|أبحث|ابحثل|إبحث|دوّر|دور\s?لي|شوف\s?لي|شوفلي|هات\s?لي|جيب\s?لي|اتفرج\s?على|راجع\s?السوق|اطلع\s?على|search|look\s?up|find\s?me|google\s?it|research)/i;

/** طلب مقارنة أو معايير أو حالة سوق — بحث فعلي حتى بلا كلمة «ابحث». */
const MARKET =
  /(قارن|مقارنة|قارنّ|مقابل|vs\b|versus|معايير\s*السوق|متوسط\s*السوق|المعدل\s*الطبيعي|benchmark|benchmarks|أسعار\s*السوق|متوسط\s*الأسعار|إيه\s*المتاح|ايه\s*المتاح|ما\s*المتاح|الخيارات\s*المتاحة|أفضل\s*الممارسات|افضل\s*الممارسات|best\s*practices|دراسة|دراسات|إحصائيات|احصائيات|statistics|أرقام\s*السوق|حصة\s*السوق|market\s*share)/i;

/** منافسون وترند — طلب واقع خارجي لا معرفة مخزّنة. */
const EXTERNAL =
  /(منافس|المنافسين|منافسينا|competitor|competitors|ترند|التريند|trend|trending|رائج|الرائج|جديد\s*في\s*السوق|الأحدث|احدث|أحدث|آخر\s*ما|جِدة|الجديد\s*في)/i;

/** كلمات زمنية: «آخر/اليوم/الآن» — إشارة قوية أن المخزون المعرفي لا يكفي. */
const RECENCY =
  /(آخر|اخر|أحدث|احدث|اليوم|النهاردة|الآن|دلوقتي|هذا\s*الأسبوع|هذا\s*الشهر|٢٠٢[5-9]|202[5-9]|الحالي|الحالية|latest|today|current|right\s*now)/i;

/**
 * منع صريح: المستخدم لا يريد بحثاً. احترامه أهم من أي إشارة أخرى —
 * فمن يقول «من معرفتك بدون بحث» ينتظر رداً فورياً لا انتظاراً لدقيقة.
 */
const SUPPRESS =
  /(بدون\s*بحث|بلا\s*بحث|من\s*غير\s*بحث|مش\s*عايز\s*بحث|من\s*معرفتك|من\s*خبرتك|بسرعة\s*بدون|no\s*search|don'?t\s*search|without\s*searching)/i;

/**
 * ثغرة معرفية: سؤال عن رقم أو قيمة خارجية لا يملكها الموظف في رأسه.
 * «كام؟ بكام؟ قد إيه؟ نسبة؟ معدل؟» — كلها أسئلة إجابتها في السوق لا في الذاكرة.
 */
const GAP =
  // «كام» كلمة قائمة بذاتها: بلا حدّ حولها تنطبق على «كامل» فينطلق بحث بلا داعٍ.
  /((?<![\p{L}])ب?كام(?![\p{L}])|قد\s*إيه|قد\s*ايه|كم\s*يكلف|كم\s*سعر|كم\s*تكلفة|ما\s*متوسط|متوسط\s*(ال)?(سعر|تكلفة|معدل)|نسبة\s*(ال)?(تحويل|فتح|ارتداد|نقر)|معدل\s*(ال)?(تحويل|فتح|نقر)|how\s*much|average\s*(cost|price|rate)|conversion\s*rate)/iu;

/**
 * شغل داخلي بحت: بياناتنا نحن لا بيانات السوق. «عروضنا، منتجاتنا، حملتنا»
 * لا تُبحث على الإنترنت — والبحث عنها يضيّع وقت المستخدم ويأتي بنتائج غريبة.
 */
const OURS =
  /(عروضنا|عرضنا|منتجاتنا|منتجنا|خدماتنا|خدمتنا|شركتنا|حملتنا|حملاتنا|صفحتنا|موقعنا|متجرنا|عملائنا|العميل|عميلنا|الزبون|فريقنا|أرقامنا|ارقامنا|مخزون|المخزون|مخزوننا|رصيد|الرصيد|فاتورة|الفاتورة|فواتيرنا|مبيعاتنا|طلباتنا|طلبيّة|طلبية|الطلبية|الطلب\b|أوردر|اوردر|موظفينا|حسابنا|بياناتنا|عندنا|لدينا|بتاعنا|بتاعتنا|بتاع\s*العميل|بتاعة\s*العميل)/i;


/** أسئلة عن العالم الخارجي: أحداث، أشخاص، رياضة، مال، صحة. */
const WORLD =
  /(خبر|أخبار|اخبار|عاجل|مباراة|ماتش|الدوري|منتخب|بورصة|سهم|أسهم|سعر\s*(ال)?(دولار|ذهب|صرف|يورو)|بيتكوين|من\s*هو|من\s*هي|مين\s*هو|مين\s*هي|ما\s*هو|ما\s*هي|إيه\s*هو|ايه\s*هو|أعراض|اعراض|who\s*is|what\s*is|news|stock)/i;

export type ResearchIntent = {
  /** هل نشغّل بحثاً حياً لهذه الرسالة؟ */
  wanted: boolean;
  /** المستخدم طلب البحث بنفسه بكلمة صريحة — نبحث حتى لو الرسالة قصيرة. */
  explicit: boolean;
  /** سبب التشغيل، للتشخيص ولاختيار المصادر. */
  reason: "explicit" | "market" | "external" | "recency" | "gap" | "suppressed" | "none";
  /** الموضوع المنقّى الذي نبحث عنه فعلاً. */
  topic: string;
};

/** ينظّف الرسالة إلى استعلام بحث قصير: بلا نداء الموظف ولا أفعال الطلب. */
export function researchTopic(message: string): string {
  return message
    .replace(/^\s*(يا\s+)?(سِراج|سراج|نور|آدم|ادم|دانة|دانه|سام|سالم|إيفا|ايفا|أمل|امل)[،,:\s]*/i, "")
    // ملاحظة: \b لا تعمل مع الحروف العربية في JS — لذلك بلا حدود كلمات هنا.
    .replace(
      /(من\s*فضلك|لو\s*سمحت|please|ابحثلي|ابحث\s*لي|ابحث|أبحث|إبحث|دوّر\s*لي|دور\s*لي|شوفلي|شوف\s*لي|هات\s*لي|جيب\s*لي|عايز|عاوز|أريد|اريد|محتاج|ممكن|search\s*for|look\s*up|find\s*me)/gi,
      " ",
    )
    // أدوات الاستفهام ليست جزءاً من الموضوع: «كام سعر النقرة» موضوعها «سعر النقرة».
    .replace(/(^|\s)(بكام|كام|قد\s*إيه|قد\s*ايه|how\s*much)(\s|$)/gi, " ")
    .replace(/^\s*(عن|على|في|حول|about|for)\s+/i, "")
    .replace(/\s+/g, " ")
    .replace(/^\s*(عن|على|في|حول)\s+/i, "")
    .replace(/[?؟!.]+\s*$/, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 140);
}

/**
 * القرار. نتجنّب البحث في الدردشة القصيرة والأسئلة عن المنصة نفسها،
 * ونبحث متى طلب المستخدم صراحةً أو متى كان الجواب الصحيح يعتمد على واقع خارجي.
 */
export function researchIntent(message: string): ResearchIntent {
  const text = (message ?? "").trim();
  const topic = researchTopic(text);
  const none: ResearchIntent = { wanted: false, explicit: false, reason: "none", topic };

  if (text.length < 8) return none;
  // أسئلة عن المنصة نفسها أو عن الموظف: لا شأن لها بالسوق الخارجي.
  if (/^(مين\s*انت|من\s*أنت|انت\s*مين|ايه\s*اللي\s*تعرف|بتعمل\s*إيه|شو\s*بتعمل)/i.test(text)) {
    return none;
  }

  // منع صريح يتقدّم على كل شيء: من قال «بدون بحث» ينتظر رداً فورياً.
  if (SUPPRESS.test(text)) return { ...none, reason: "suppressed" };

  // شغل داخلي بحت («ابحث عن أسعار خدماتنا»): بياناتنا ليست على الإنترنت،
  // والبحث عنها تأخير يأتي بنتائج غريبة — يتقدّم حتى على فعل البحث الصريح.
  // تُستثنى المقارنة الصريحة بالسوق أو ذكر منافس/ترند.
  if (OURS.test(text) && !MARKET.test(text) && !EXTERNAL.test(text)) return none;

  if (EXPLICIT.test(text)) return { wanted: true, explicit: true, reason: "explicit", topic };

  if (MARKET.test(text)) return { wanted: true, explicit: false, reason: "market", topic };
  if (EXTERNAL.test(text)) return { wanted: true, explicit: false, reason: "external", topic };
  // ثغرة معرفية: سؤال عن رقم أو معدّل لا يملكه الموظف — الجواب في السوق لا في ذاكرته.
  if (GAP.test(text)) return { wanted: true, explicit: false, reason: "gap", topic };
  // الكلمات الزمنية وحدها تكفي فقط في رسالة ذات محتوى، لا في «عامل إيه النهاردة؟».
  if (RECENCY.test(text) && text.length > 24) {
    return { wanted: true, explicit: false, reason: "recency", topic };
  }
  // أسئلة عن العالم نفسه (خبر، مباراة، بورصة، صحة، «مين هو/إيه هو»): إجابتها في الواقع لا في الذاكرة.
  if (topic.length >= 4 && WORLD.test(text)) {
    return { wanted: true, explicit: false, reason: "external", topic };
  }
  return none;
}
