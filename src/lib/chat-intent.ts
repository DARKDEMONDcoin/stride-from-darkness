/**
 * تصنيف نيّة الرسالة: هل المستخدم يطلب مخرجاً جاهزاً للنشر/الإرسال، أم يسأل سؤالاً
 * أو يتحدث حديثاً عادياً؟ في الحالة الثانية يجيب الموظف كإنسان ذكي فقط — بلا مخرج
 * ولا لوحة نشر ولا صورة ولا طلب ربط حساب.
 */

export type ChatIntent = "smalltalk" | "question" | "work";

/** أفعال طلب مخرج فعلي. */
const WORK =
  /منشور|بوست|بوستات|كابشن|كاربشن|كاروسيل|ريل|ريلز|قصة|ستوري|تغريدة|ثريد|مقال|خطة|تقويم|كالندر|حملة|سكربت|سيناريو|إعلان|اعلان|بريد|إيميل|ايميل|رسالة تسويقية|صفحة هبوط|تصميم|صورة|فيديو|هاشتاق|هاشتاجات|جدول|جدولة|انشر|أنشر|نشر|اكتب|اكتبلي|اعملي|اعمل لي|جهّز|جهز|صمم|ولّد|ولد لي|حلّل|حلل|تحليل|تقرير|فحص|افحص|بحث كلمات|ترتيب|أفكار|افكار/u;

/**
 * طلب صورة صريح: «ولدلي صورة»، «اعمل تصميم»، «بوستر»، «شعار»… في هذه الحالة
 * تُولَّد صورة فعلية أياً كان الموظف، ولا يُكتفى بوصف الصورة نصاً.
 */
const IMAGE_REQUEST =
  /(صورة|صور|صورًا|صوره|تصميم|تصاميم|ديزاين|بوستر|بروشور|ملصق|بانر|بنر|انفوجراف|إنفوجراف|لوجو|شعار|كرييتف|كريتف|غلاف|كوفر|مشهد|رسمة|رسم|illustration|image|design|poster|banner|logo|thumbnail)/iu;

/** أفعال توليد/إنشاء تجعل طلب الصورة صريحاً لا مجرد ذكر لكلمة صورة. */
const MAKE =
  /(ولّد|ولد|ولدلي|ولّدلي|اعمل|إعمل|اعملي|سوّ|سو لي|سويلي|صمم|صمّم|ارسم|إرسم|اصنع|أنشئ|انشئ|جهّز|جهز|اكتبلي|عايز|عاوز|أريد|اريد|ابغى|أبغى|هات|اعطني|أعطني|create|generate|make|draw|design)/iu;

/**
 * رفض صريح للصورة: «بدون صورة»، «نص فقط»، «بلا تصميم»… وجودها يمنع أي توليد
 * حتى لو ذكر المستخدم كلمة صورة في نفس الرسالة.
 */
const NO_IMAGE =
  /(بدون|بلا|من\s*غير|مش\s*عايز|ما\s*أبغى|لا\s*أريد|بدون\s*ما\s*تعمل)\s*(صور[ةه]?|صور|تصميم|تصاميم|وسائط|ميديا|بوستر|جرافيك)|نص\s*(فقط|بس)|كتاب[ةه]\s*فقط|no\s*image|text\s*only|without\s*(an?\s*)?image/iu;

/** هل طلب المستخدم صراحةً عدم إرفاق صورة؟ */
export function refusesImageRequest(message: string): boolean {
  return NO_IMAGE.test((message ?? "").trim());
}

/** هل الرسالة طلب صورة صريح؟ */
export function wantsImageRequest(message: string): boolean {
  const text = (message ?? "").trim();
  if (!text) return false;
  if (refusesImageRequest(text)) return false;
  if (!IMAGE_REQUEST.test(text)) return false;
  // ذكر كلمة «صورة» وحدها في سؤال ليس طلب توليد.
  return MAKE.test(text) || /^\s*(صورة|تصميم|بوستر|شعار|بانر)/u.test(text);
}

/** تحيات وحديث اجتماعي قصير. */
const SMALL =
  /^(\s*[\p{P}\p{S}]*\s*)?(هاي|هلا|أهلا|اهلا|أهلاً|السلام عليكم|سلام|صباح الخير|مساء الخير|ازيك|إزيك|كيفك|كيف حالك|عامل ايه|عامل إيه|شكرا|شكراً|تمام|تسلم|يعطيك العافية|ok|okay|hi|hello|thanks)(?![\p{L}])/iu;

/**
 * يصنّف الرسالة. القاعدة: أي طلب فيه فعل إنتاج = عمل. غير ذلك سؤال أو دردشة،
 * ويجيب الموظف عليه مباشرة بذكاء بلا فرض خدماته.
 */
/** صيغ الاستفهام في أول الرسالة. */
const ASK_START =
  /^(مين|من|ايه|إيه|ما هو|ما هي|ما|كام|كم|ليه|لماذا|امتى|إمتى|متى|فين|أين|وين|هل|ازاي|إزاي|كيف|أفضل|افضل|احسن|أحسن|يعني)(?![\p{L}])/u;

/** فعل إنتاج صريح: يعني «سلّم لي الشيء» لا «أخبرني عنه». */
const PRODUCE =
  /(تكتب|تعمل|تصمّم|تصمم|تجهّز|تجهز|تولّد|تولد|تحلّل|تحلل|تنشر|اكتب|أكتب|اكتبلي|اعمل|إعمل|اعملي|سوّ|سويلي|جهّز|جهز|صمم|صمّم|ولّد|ولد لي|ولدلي|أنشئ|انشئ|ارسم|حضّر|حضر|انشر|أنشر|اجدول|جدول لي|حلّل|حلل|افحص|اعطني|أعطني|هات|عايز|عاوز|أريد|اريد|ابغى|أبغى|محتاج|create|generate|write|make|design)/iu;

/**
 * أفعال تنفيذ فعلية (بلا أفعال الرغبة «عايز/أريد/محتاج») — وجودها يعني تسليم شيء.
 */
const ACTION_PRODUCE =
  /(تكتب|تعمل|تصمّم|تصمم|تجهّز|تجهز|تولّد|تولد|تنشر|اكتب|أكتب|اكتبلي|اعمل|إعمل|اعملي|سوّ|سويلي|جهّز|جهز|صمم|صمّم|ولّد|ولدلي|أنشئ|انشئ|ارسم|حضّر|حضر|انشر|أنشر|اجدول|افحص|create|generate|write|make|design)/iu;

/** طلب رأي أو معرفة: استشارة لا تسليم. */
const ADVISORY =
  /(رأيك|رايك|نصيحتك|تنصح|تنصحني|عايز اعرف|عاوز اعرف|أريد أن أعرف|اعرف رأيك|استشارة|وجهة نظرك|شايف ايه|شايف إيه)/iu;

export function chatIntent(message: string): ChatIntent {
  const text = message.trim();
  if (!text) return "smalltalk";
  // سؤال استشاري («ايه أحسن وقت للنشر؟») ليس طلب مخرج حتى لو ذكر كلمة من مجال العمل.
  const looksLikeQuestion = /[؟?]\s*$/.test(text) || ASK_START.test(text);
  // داخل صيغة سؤال، فعل الإنتاج يُحتسب إن كان في أول الرسالة، أو متبوعاً بـ«لي/لنا»،
  // أو كان فعل تنفيذ صريح مع اسم مخرج («ممكن تعمل تحليل سريع لحسابي؟»).
  const producesNow =
    new RegExp(`^\\s*${PRODUCE.source}`, "iu").test(text) ||
    new RegExp(`${PRODUCE.source}\\s*(لي|لنا|لى)`, "iu").test(text) ||
    (ACTION_PRODUCE.test(text) && WORK.test(text) && !ADVISORY.test(text));
  if (looksLikeQuestion && !producesNow) return "question";
  // ذكر اسم مجال («الحملة») داخل طلب رأي ليس طلب تنفيذ.
  if (ADVISORY.test(text) && !ACTION_PRODUCE.test(text)) return "question";
  if (WORK.test(text)) return "work";

  if (SMALL.test(text) && text.length < 60) return "smalltalk";
  if (
    /[؟?]\s*$/.test(text) ||
    /^(مين|من|ايه|إيه|ما هو|ما هي|كام|كم|ليه|لماذا|امتى|إمتى|متى|فين|أين|وين|هل|ازاي|إزاي|كيف)(?![\p{L}])/u.test(
      text,
    )
  )
    return "question";
  return text.length > 160 ? "work" : "question";
}

/** التعليمات التي تُحقن حسب النية. */
export function intentBlock(intent: ChatIntent): string {
  if (intent === "work") return "";
  return [
    "## وضع المحادثة الحرة (إلزامي في هذه الرسالة)",
    intent === "smalltalk"
      ? "المستخدم يحادثك حديثاً عادياً. رد بجملة أو جملتين دافئتين بشريتين فقط."
      : "المستخدم يسألك سؤالاً ولم يطلب منك إنتاج شيء. أجب على السؤال نفسه إجابة مباشرة دقيقة مفيدة، بأقصر شكل يكفيه، مستنداً إلى الحقائق اللحظية إن وُجدت.",
    "ممنوع في هذه الرسالة: كتابة منشور أو مخرج جاهز، أو عرض خدماتك وقدراتك، أو ذكر النشر والجدولة والاعتماد، أو طلب ربط أي حساب، أو إضافة «الخطوة التالية»، أو توليد صورة.",
    'اجعل "deliverable" و"deliverables" و"needs_connection" و"image_prompt" كلها null.',
    "لا تفرض على المستخدم شيئاً لم يطلبه. إن كان لديك اقتراح مفيد جداً فاذكره كسؤال قصير في سطر واحد فقط عند الحاجة.",
  ].join("\n");
}
