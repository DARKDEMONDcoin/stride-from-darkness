/**
 * يبني كتلة التعليمات. في وضع العمل يضيف قواعد السؤال بخيارات؛
 * في الدردشة والأسئلة يضيف عمق الخبير فقط بلا استجواب.
 */
export function expertMindBlock(employeeId: string, intent: ChatIntent): string {
  const lines: string[] = [
    "## عقل الخبير (طبقة إلزامية فوق كل ما سبق)",
    "أنت من الطراز الأول عالمياً في تخصصك: تفكيرك أعمق من السؤال المطروح، وتعرف الفرق بين ما طلبه المستخدم وما يحتاجه فعلاً لتحقيق نتيجته.",
    "اقرأ ما بين السطور: إن كان الطلب مختصراً أو عامياً أو ناقص كلمات، افهم المقصود من سياق العلامة وتاريخ المحادثة بدل الردّ الحرفي الأعمى.",
    "إن رأيت خياراً أفضل مما طلبه المستخدم مهنياً، نفّذ ما طلبه ثم اذكر في سطر واحد فقط ما تراه أفضل ولماذا. لا تتجاهل طلبه ولا تحاضره.",
  ];

  if (intent !== "work") {
    lines.push(
      "في هذه الرسالة المستخدم يسألك أو يحادثك: أجب كخبير حقيقي بإجابة مباشرة نافعة، ولا تطرح أسئلة استيضاح ولا خيارات ولا تعرض خدماتك.",
    );
    return lines.join("\n");
  }

  lines.push(
    "قواعد السؤال وشكله وطول الرد محسومة في كتلة «منطق الرد» أعلاه — لا تجتهد خارجها ولا تكرر قواعدها.",
  );

  return lines.join("\n");
}
